//! Regenerate the Poseidon constant tables from light-poseidon's circom-compatible parameters.
//!
//!   cargo run -p shadenode --example gen_poseidon -- 3 > crates/shadenode/src/poseidon_t3.rs
//!   cargo run -p shadenode --example gen_poseidon -- 2 > crates/shadenode/src/poseidon_t2.rs
use ark_bn254::Fr;
use ark_ff::{BigInteger, PrimeField};
use num_bigint::BigUint;

fn dec(f: &Fr) -> String {
    BigUint::from_bytes_be(&f.into_bigint().to_bytes_be()).to_str_radix(10)
}

fn main() {
    let width: u8 = std::env::args()
        .nth(1)
        .and_then(|w| w.parse().ok())
        .unwrap_or(3);
    let params =
        light_poseidon::parameters::bn254_x5::get_poseidon_parameters::<Fr>(width).unwrap();
    println!(
        "//! Poseidon constants for BN254, width {width} ({} input{}), x^5 S-box: circomlib's parameters.",
        width - 1,
        if width == 2 { "" } else { "s" }
    );
    println!("//!");
    println!(
        "//! Generated by `cargo run -p shadenode --example gen_poseidon -- {width}`. Do not edit."
    );
    println!();
    println!("use ark_bn254::Fr;");
    println!("use ark_ff::MontFp;");
    println!();
    println!("pub const FULL_ROUNDS: usize = {};", params.full_rounds);
    println!(
        "pub const PARTIAL_ROUNDS: usize = {};",
        params.partial_rounds
    );
    println!();
    println!("pub const ARK: [Fr; {}] = [", params.ark.len());
    for c in &params.ark {
        println!("    MontFp!(\"{}\"),", dec(c));
    }
    println!("];");
    println!();
    println!("pub const MDS: [[Fr; {width}]; {width}] = [");
    for row in &params.mds {
        println!("    [");
        for c in row {
            println!("        MontFp!(\"{}\"),", dec(c));
        }
        println!("    ],");
    }
    println!("];");
}
