#!/usr/bin/env python3
"""Generate crates/microtor/src/bootstrap_data.rs from Tor's auth_dirs.inc and fallback_dirs.inc.

Usage: gen_bootstrap.py <auth_dirs.inc> <fallback_dirs.inc> > bootstrap_data.rs
The inputs are the files at src/app/config/ in https://gitlab.torproject.org/tpo/core/tor.
"""
import re
import sys


def hexbytes(h):
    h = h.replace(" ", "")
    return ", ".join(f"0x{h[i:i+2].lower()}" for i in range(0, len(h), 2))


def ip(v):
    return ", ".join(v.split("."))


auth_text = open(sys.argv[1]).read()
fallback_text = open(sys.argv[2]).read()

# Each authority is a run of adjacent C string literals ending in a comma.
entries = []
for block in re.split(r'",\s*\n', auth_text):
    line = "".join(re.findall(r'"([^"]*)"?', block + '"'))
    m = re.match(
        r"(\w+) orport=(\d+) (?:bridge )?(?:v3ident=([0-9A-F]{40}) )?(?:ipv6=\S+ )?"
        r"(\d+\.\d+\.\d+\.\d+):(\d+) ([0-9A-F ]+)",
        line,
    )
    if not m or not m.group(3):
        continue  # bridge authority: no v3 identity, signs no consensus
    name, orport, v3ident, addr, _dirport, fp = m.groups()
    entries.append((name, v3ident, addr, int(orport), fp))

fallbacks = re.findall(
    r'^"(\d+\.\d+\.\d+\.\d+) orport=(\d+) id=([0-9A-F]{40})"', fallback_text, re.M
)

print("//! Directory authorities and fallback directory mirrors.")
print("//!")
print("//! Generated by tools/gen_bootstrap.py from Tor's auth_dirs.inc and fallback_dirs.inc.")
print("//! Do not edit by hand; regenerate when Tor rotates an authority.")
print()
print("pub struct Authority {")
print("    pub name: &'static str,")
print("    /// SHA-1 of the authority's long-term v3 identity key.")
print("    pub v3ident: [u8; 20],")
print("    pub ip: [u8; 4],")
print("    pub or_port: u16,")
print("}")
print()
print("pub struct Fallback {")
print("    pub ip: [u8; 4],")
print("    pub or_port: u16,")
print("}")
print()
print(f"pub const AUTHORITIES: [Authority; {len(entries)}] = [")
for name, v3ident, addr, orport, _fp in entries:
    print("    Authority {")
    print(f'        name: "{name}",')
    print(f"        v3ident: [{hexbytes(v3ident)}],")
    print(f"        ip: [{ip(addr)}],")
    print(f"        or_port: {orport},")
    print("    },")
print("];")
print()
print(f"pub const FALLBACKS: [Fallback; {len(fallbacks)}] = [")
for addr, orport, _fp in fallbacks:
    print(f"    Fallback {{ ip: [{ip(addr)}], or_port: {orport} }},")
print("];")
