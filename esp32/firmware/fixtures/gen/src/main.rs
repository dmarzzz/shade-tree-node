//! Host-side fixture generator for the ESP32 verifier benchmark.
//!
//! Builds one real RLN envelope proof with the upstream prover (same inputs as the upstream
//! test `a_real_envelope_proof_round_trips_through_json_and_verifies`), verifies it on the
//! host with the upstream verifier, and writes:
//!   <out>/proof.json     {"proof": {...}, "publicSignals": {...}, "publicInputsOrder": [...]}
//!   <out>/envelope.json  a full v4 wire envelope, framed like crates/shadenet/src/transport.rs
use shadenet_rln::prover::{build_envelope, embedded_bytes, EnvelopeInput};
use shadenet_rln::tree::{fr_to_dec, parse_fr, rate_commitment};
use shadenet_rln::verify::{parse_proof, verify, VerifyingKey};

const EPOCH: u64 = 7;

fn main() {
    let out = std::env::args().nth(1).expect("usage: fixture-gen <out-dir>");
    let leaf = fr_to_dec(&rate_commitment(parse_fr("111").unwrap(), 8));
    let built = build_envelope(&EnvelopeInput {
        identity_secret: "111".into(),
        member_leaf: leaf.clone(),
        members: vec![leaf],
        target: "example.com:443".into(),
        nonce: "00112233445566778899aabbccddeeff".into(),
        signal: None,
        epoch: EPOCH,
        rln_identifier: "1".into(),
        user_message_limit: 8,
        message_id: 0,
        circuits_dir: None,
    })
    .expect("build envelope");

    // Host verification with the upstream verifier (the code vendored into the firmware).
    let vkey_bytes = embedded_bytes().vkey;
    let vkey_json: serde_json::Value = serde_json::from_slice(vkey_bytes).unwrap();
    let key = VerifyingKey::parse(&vkey_json).unwrap();
    let proof = parse_proof(&built.proof).unwrap();
    let order = ["y", "root", "nullifier", "x", "externalNullifier"];
    let inputs: Vec<_> = order
        .iter()
        .map(|name| parse_fr(built.public_signals[*name].as_str().unwrap()).unwrap())
        .collect();
    assert!(verify(&key, &proof, &inputs).unwrap(), "host verify failed");
    let mut wrong = inputs.clone();
    wrong[3] = parse_fr("1").unwrap();
    assert!(!verify(&key, &proof, &wrong).unwrap(), "tampered input accepted");

    let fixture = serde_json::json!({
        "_note": "RLN Groth16 proof for circuits/rln/verification_key.json; identity_secret=111, limit=8, depth-20 tree with one member, target example.com:443, epoch 7, rlnIdentifier 1, messageId 0. Generated by fixtures/gen with the upstream shadenet-rln prover.",
        "epoch": EPOCH,
        "publicInputsOrder": order,
        "proof": built.proof,
        "publicSignals": built.public_signals,
    });
    std::fs::write(
        format!("{out}/proof.json"),
        serde_json::to_string_pretty(&fixture).unwrap() + "\n",
    )
    .unwrap();

    let artifact = shadenet_proto::artifact_id_of("rln", vkey_bytes);
    let envelope = serde_json::json!({
        "v": shadenet_proto::PROTO_MAX,
        "artifact": artifact,
        "proof": {
            "snarkProof": { "proof": built.proof, "publicSignals": built.public_signals },
            "epoch": built.epoch,
            "rlnIdentifier": built.rln_identifier,
        },
        "nullifier": built.nullifier,
        "externalNullifier": built.external_nullifier,
        "share": { "x": built.share_x, "y": built.share_y },
        "target": built.target,
        "nonce": built.nonce,
    });
    // One line + "\n", exactly as the client writes it to the wire.
    std::fs::write(
        format!("{out}/envelope.json"),
        serde_json::to_string(&envelope).unwrap() + "\n",
    )
    .unwrap();
    println!("host verify OK; wrote {out}/proof.json and {out}/envelope.json");
}
