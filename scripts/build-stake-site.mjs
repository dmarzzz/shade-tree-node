// Builds the Get access page from the network record:
//   docs/post/stake/stake.js          bundled flow (esbuild); the SDK + prover split into
//                                     docs/post/stake/chunks/, loaded only on exit or withdraw
//   docs/post/stake/zk/withdraw.*     the withdraw circuit the in-browser prover runs
//   docs/post/stake/index.html        rendered by site-src/stake-page.mjs
//   docs/post/api/_stake-profile.mjs  the contract + RPC the same-origin status API reads
// and writes the shared primary nav into every secondary page.
//   node scripts/build-stake-site.mjs          write
//   node scripts/build-stake-site.mjs --check  exit 1 if any committed output is stale
// A page for another record (the staging rehearsal) builds from network/<name>/deployment.json
// into a separate tree, leaving the committed site alone:
//   SHADENET_SITE_NETWORK=sepolia-staging SHADENET_SITE_OUT=/tmp/site node scripts/build-stake-site.mjs
import { build } from "esbuild";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import { basename, dirname, join, relative as relativePath, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const stale = [];

// Which record the page is built from, and where the output goes (default: the committed site).
export const SITE_NETWORK = process.env.SHADENET_SITE_NETWORK || "sepolia";
const RECORD_PATH = join(root, "network", SITE_NETWORK, "deployment.json");
const outRoot = process.env.SHADENET_SITE_OUT ? resolve(process.env.SHADENET_SITE_OUT) : root;
if (check && (SITE_NETWORK !== "sepolia" || outRoot !== root)) {
  console.error("--check compares the committed site only: unset SHADENET_SITE_NETWORK and SHADENET_SITE_OUT");
  process.exit(2);
}
if (SITE_NETWORK !== "sepolia") readFileSync(RECORD_PATH); // fail early on an unknown record
// The page renderer imports network/sepolia/deployment.json; point that at the chosen record.
if (SITE_NETWORK !== "sepolia") register("./site-record-loader.mjs", { parentURL: import.meta.url, data: { network: SITE_NETWORK } });
const { renderStakePage } = await import("../site-src/stake-page.mjs");
const { navLinks } = await import("../site-src/site-nav.mjs");

export const BUNDLE_OPTIONS = {
  entryPoints: { stake: join(root, "site-src", "stake-entry.mjs") },
  outdir: join(root, "docs", "post", "stake"),
  chunkNames: "chunks/[name]-[hash]",
  splitting: true,
  platform: "browser",
  bundle: true,
  format: "esm",
  minify: true,
  legalComments: "eof",
  sourcemap: false,
  target: ["chrome109", "firefox115", "safari16.4"],
  write: false,
  plugins: [{
    name: "shadenet-site-record",
    setup(api) {
      api.onResolve({ filter: /network\/sepolia\/deployment\.json$/ }, () => ({ path: RECORD_PATH }));
    },
  }],
};

// Pages whose primary nav is the shared one, and which item each page marks as current.
// Relative pages also open as direct-file previews, so their links must not be root-absolute.
export const NAV_PAGES = [
  ["docs/post/agent/index.html", "agent", false],
  ["docs/post/operator/index.html", "operator", false],
  ["docs/post/lab/index.html", "lab", true],
  ["docs/post/grove/index.html", "canopy", true],
  ["docs/post/404.html", null, false],
];

export function stakeProfileModule() {
  const deployment = JSON.parse(readFileSync(RECORD_PATH, "utf8"));
  const staked = deployment.admission.roots.staked;
  const profile = {
    network: deployment.network,
    chainId: staked.chainId,
    contract: staked.contract,
    rpcUrl: staked.rpcUrl,
    deployBlock: staked.deployBlock,
    tiers: staked.tiers,
  };
  return `// Generated by scripts/build-stake-site.mjs from network/${SITE_NETWORK}/deployment.json. Do not edit.\nexport default ${JSON.stringify(profile, null, 2)};\n`;
}

export function withSharedNav(html, current, relative) {
  const match = html.match(/^([ \t]*)<div class="nav-links">[\s\S]*?\n\1<\/div>/m);
  if (!match) throw new Error("page has no nav-links block");
  return html.replace(match[0], navLinks(current, match[1], { relative }));
}

// The withdraw circuit, served same-origin for the in-browser exit/withdraw prover. Copied from
// circuits/rln so the ceremony's new zkey reaches the page on the next build.
export const PROVER_ARTIFACTS = [
  ["circuits/rln/withdraw.wasm", "docs/post/stake/zk/withdraw.wasm"],
  ["circuits/rln/withdraw_final.zkey", "docs/post/stake/zk/withdraw_final.zkey"],
];

function emit(relative, contents) {
  const path = join(outRoot, relative);
  mkdirSync(dirname(path), { recursive: true });
  let current = null;
  try { current = readFileSync(path); } catch {}
  const next = Buffer.isBuffer(contents) ? contents : Buffer.from(contents);
  if (current && Buffer.compare(current, next) === 0) return;
  if (check) stale.push(relative);
  else writeFileSync(path, next);
}

const bundled = await build(BUNDLE_OPTIONS);
const chunkDir = join(outRoot, "docs/post/stake/chunks");
const wanted = new Set();
for (const file of bundled.outputFiles) {
  const rel = relativePath(root, file.path);
  if (rel.includes("/chunks/")) wanted.add(basename(rel));
  emit(rel, Buffer.from(file.contents));
}
let present = [];
try { present = readdirSync(chunkDir); } catch {}
for (const name of present.filter((n) => !wanted.has(n))) {
  if (check) stale.push(`docs/post/stake/chunks/${name} (orphaned)`);
  else rmSync(join(chunkDir, name));
}
for (const [from, to] of PROVER_ARTIFACTS) emit(to, readFileSync(join(root, from)));
emit("docs/post/stake/index.html", renderStakePage());
emit("docs/post/api/_stake-profile.mjs", stakeProfileModule());
for (const [page, current, relative] of NAV_PAGES) {
  emit(page, withSharedNav(readFileSync(join(root, page), "utf8"), current, relative));
}

if (stale.length) {
  console.error(`stale generated site files (run node scripts/build-stake-site.mjs):\n  ${stale.join("\n  ")}`);
  process.exit(1);
}
console.log(check ? "site build: up to date" : `site build: written (${SITE_NETWORK}${outRoot === root ? "" : ` -> ${outRoot}`})`);
